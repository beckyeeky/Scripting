export function resolveSFSymbolGlyph(name: string): string {
  if (!name) return "•"
  if (SF_SYMBOL_MAP[name]) return SF_SYMBOL_MAP[name]
  if (name.endsWith(".fill")) {
    const base = name.slice(0, -5)
    if (SF_SYMBOL_MAP[base]) return SF_SYMBOL_MAP[base]
  }
  return "•"
}

export function SFSymbolIcon({
  name,
  size = 17,
  color = "#007AFF",
  style,
}: {
  name: string
  size?: number
  color?: string
  style?: any
}) {
  const glyph = resolveSFSymbolGlyph(name)
  const adjustedSize = glyph.length > 1 ? Math.max(10, Math.round(size * 0.72)) : size
  return (
    <RNText
      allowFontScaling={false}
      style={[
        {
          fontSize: adjustedSize,
          color,
          lineHeight: Math.round(size * 1.18),
          textAlign: "center",
          fontWeight: "500",
        },
        style,
      ]}
    >
      {glyph}
    </RNText>
  )
}
